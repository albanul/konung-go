// Package sitenav ties the HTML outputs of the command-line tools into one
// browsable site. Each tool writes its page into a section directory under a
// shared root (default output/site) and calls WriteHub to refresh the landing
// page:
//
//	output/site/index.html          landing page (sections that exist)
//	output/site/maps/index.html     cmd/map-render -all
//	output/site/sprites/index.html  cmd/sprite-catalog
package sitenav

import (
	"fmt"
	"html/template"
	"os"
	"path/filepath"
	"strings"
)

// DefaultRoot is the site root used by the tools' default output paths.
const DefaultRoot = "output/site"

// Section is one tool's page in the site.
type Section struct {
	Dir, Title, Description, Command string
}

// Sections lists the known site sections in navigation order.
var Sections = []Section{
	{"maps", "Maps", "Every KONUNG.N map rendered with terrain, decorations, shadows and static objects.", "go run ./cmd/map-render -all output/site/maps"},
	{"sprites", "Sprites", "Every indexed image resource and animation frame, searchable by ID, label, and offset.", "go run ./cmd/sprite-catalog"},
}

// Style is CSS for the navigation bar; include it in each page's <style>.
const Style = `.sitenav{display:flex;gap:4px;align-items:center;margin:-8px 0 16px;padding:6px 8px;background:#2a2e33;border-radius:6px;font:14px system-ui}
.sitenav a{color:#cfd6de;text-decoration:none;padding:4px 10px;border-radius:4px}.sitenav a:hover{background:#3a4047}
.sitenav a.current{background:#4a5560;color:#fff}.sitenav .brand{font-weight:bold;margin-right:8px}`

// Nav returns the navigation bar for a page in section current ("" for the
// landing page). Links are relative, so the site works from file://.
func Nav(current string) template.HTML {
	up := "../"
	if current == "" {
		up = ""
	}
	var b strings.Builder
	fmt.Fprintf(&b, `<nav class="sitenav"><a class="brand" href="%sindex.html">Konung</a>`, up)
	for _, s := range Sections {
		class := ""
		if s.Dir == current {
			class = ` class="current"`
		}
		fmt.Fprintf(&b, `<a%s href="%s%s/index.html">%s</a>`, class, up, s.Dir, template.HTMLEscapeString(s.Title))
	}
	b.WriteString(`</nav>`)
	return template.HTML(b.String())
}

// SectionRoot returns the site root for a section written to dir when dir is
// a known section directory (e.g. output/site/maps), and false otherwise.
func SectionRoot(dir string) (string, bool) {
	base := filepath.Base(filepath.Clean(dir))
	for _, s := range Sections {
		if s.Dir == base {
			return filepath.Dir(filepath.Clean(dir)), true
		}
	}
	return "", false
}

type hubEntry struct {
	Section
	Built bool
}

// WriteHub (re)writes root/index.html, linking every section and marking
// those whose index.html has not been generated yet.
func WriteHub(root string) error {
	var entries []hubEntry
	for _, s := range Sections {
		_, err := os.Stat(filepath.Join(root, s.Dir, "index.html"))
		entries = append(entries, hubEntry{s, err == nil})
	}
	f, err := os.Create(filepath.Join(root, "index.html"))
	if err != nil {
		return err
	}
	defer f.Close()
	return hubTemplate.Execute(f, struct {
		Style    template.CSS
		Nav      template.HTML
		Sections []hubEntry
	}{template.CSS(Style), Nav(""), entries})
}

var hubTemplate = template.Must(template.New("hub").Parse(`<!doctype html>
<html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width">
<title>Konung resource explorer</title>
<style>
body{font:14px system-ui;margin:20px;background:#1d2024;color:#eee}
{{.Style}}
.cards{display:grid;grid-template-columns:repeat(auto-fill,minmax(280px,1fr));gap:12px;max-width:1000px}
.card{background:#30353b;padding:14px;border-radius:6px}.card a{color:#9cc8ff}.card h2{margin:0 0 8px}
code{background:#25292e;padding:2px 4px;border-radius:3px;font-size:12px}.muted{color:#aab2bb}
</style></head><body>
{{.Nav}}
<h1>Konung resource explorer</h1>
<p class="muted">Generated from the installed game assets. Each section is regenerated by its own tool.</p>
<div class="cards">{{range .Sections}}
<div class="card"><h2>{{if .Built}}<a href="{{.Dir}}/index.html">{{.Title}}</a>{{else}}{{.Title}}{{end}}</h2>
<p>{{.Description}}</p>{{if not .Built}}<p class="muted">Not generated yet. Run:</p>{{end}}<p><code>{{.Command}}</code></p></div>{{end}}
</div>
</body></html>
`))
